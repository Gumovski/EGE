#Все 5-буквенные слова, составленные из букв Б, В, Г, записаны в обратном алфавитном порядке. Вот начало списка:

#1)ГГГГГ
#2)ГГГГВ
#3)ГГГГБ
#4)ГГГВГ

#На каком месте от начала списка находится слово ВГБГВ?

from itertools import product

count = 1
for p in product('ГВБ', repeat=5):
    if ''.join(p) == 'ВГБГВ':
        break
    count += 1
print(count)