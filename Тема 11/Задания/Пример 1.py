#Пароль состоит из 18 символов, используется алфавит из 70 символов. Кодирование посимвольное,
# все символы кодируются одинаковым минимальным числом бит,
#каждый пароль занимает целое минимальное число байт. Сколько Кбайт потребуется для хранения 1024 паролей?

# 2^j >= 70 (N)
j = 7
l = 18
c = 1024
bats = (l * j) / 8
bats = 16
I = c * bats / 1024
print(I)
